import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$; grant usage on schema auth to anon,authenticated; grant execute on function auth.uid() to anon,authenticated;`);
const sql=await fs.readFile('schema.sql','utf8');
await db.exec(sql.split('insert into storage.buckets')[0]);
const owner='11111111-1111-1111-1111-111111111111',other='22222222-2222-2222-2222-222222222222';
await db.exec(`insert into auth.users values('${owner}'),('${other}');insert into public.menu_owners values('${owner}');`);
await db.exec('set role anon');
assert.equal((await db.query('select * from menu_public')).rows.length,1);
await assert.rejects(db.query('select * from menu_drafts'));
await assert.rejects(db.query("update menu_public set content='{}'"));
await assert.rejects(db.query("select save_menu('{}',1,true)"));
await db.exec(`reset role;set role authenticated;set request.jwt.claim.sub='${other}';`);
assert.equal((await db.query('select * from menu_drafts')).rows.length,0);
await assert.rejects(db.query("select save_menu('{}',1,true)"),/FORBIDDEN/);
await db.exec(`set request.jwt.claim.sub='${owner}'`);
const seed=JSON.parse(await fs.readFile('dist/seed.json','utf8'));
let draft=structuredClone(seed);draft.products[0].price=475000;
await db.query('select save_menu($1::jsonb,1,false)',[JSON.stringify(draft)]);
assert.equal((await db.query("select content->'products'->0->>'price' as price from menu_public")).rows[0].price,'450000');
await assert.rejects(db.query('select save_menu($1::jsonb,1,true)',[JSON.stringify(seed)]),/CONFLICT/);
draft.products[1].visible=false;draft.products[2].deleted=true;
await db.query('select save_menu($1::jsonb,2,true)',[JSON.stringify(draft)]);
const pub=(await db.query('select content from menu_public')).rows[0].content;
assert.equal(pub.products[0].price,475000);assert.equal(pub.products.length,18);assert.equal(pub.products.filter(p=>p.price===null).length,6);
let invalid=structuredClone(draft);invalid.products[0].price=-1;
await assert.rejects(db.query('select save_menu($1::jsonb,3,true)',[JSON.stringify(invalid)]),/Invalid price/);
assert.equal((await db.query('select revision from menu_drafts')).rows[0].revision,3);
await assert.rejects(db.query("update menu_drafts set content='{}'"));
console.log('Passed: anonymous read-only access; owner allowlist; draft isolation; atomic publish; conflict protection; nullable prices; invisible item exclusion; invalid price rollback.');
await db.close();
